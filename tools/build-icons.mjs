// Extracts the Lucide icons Fabriqon uses into js/icons.js so the app ships
// only what it needs and never depends on a CDN.
// Usage: node tools/build-icons.mjs <path-to-node_modules/lucide>
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lucideDir = process.argv[2];
if (!lucideDir) {
  console.error('Pass the path to the lucide package');
  process.exit(1);
}

const ICONS = `layout-dashboard users ruler shirt clipboard-list factory calculator package wallet
calendar chart-column sparkles message-square settings plus search x chevron-left chevron-right
chevron-down menu bell sun moon trash-2 pencil archive archive-restore eye download upload printer
file-text file-spreadsheet phone mail map-pin user user-plus check circle-check triangle-alert info
clock wifi-off wifi refresh-cw lock lock-open log-out image camera scissors copy send arrow-right
arrow-left ellipsis filter database hard-drive shield-check palette layers receipt credit-card
banknote trending-up trending-down package-plus package-minus truck history list square-kanban
layout-grid calendar-days calendar-plus sliders-horizontal star tag external-link panel-left-close
panel-left-open house wand-sparkles book-open bot key-round minus undo-2 grip-vertical
circle-dollar-sign shopping-bag box gauge clipboard-check flag circle-alert git-compare-arrows
smartphone monitor save`.split(/\s+/).filter(Boolean);

const out = {};
const missing = [];
for (const name of ICONS) {
  const file = join(lucideDir, 'dist', 'esm', 'icons', `${name}.js`);
  if (!existsSync(file)) { missing.push(name); continue; }
  const src = readFileSync(file, 'utf8');
  const m = src.match(/const \w+ = (\[[\s\S]*?\]);\s*\n\s*export/);
  if (!m) { missing.push(name); continue; }
  const node = new Function('defaultAttributes', `return ${m[1]};`)({});
  out[name] = node[2]; // children: [tag, attrs][]
}
if (missing.length) {
  console.error('Missing icons:', missing.join(', '));
  process.exit(1);
}

const banner = `// Generated by tools/build-icons.mjs from lucide (ISC licence). Do not edit by hand.\n`;
writeFileSync(join(root, 'js', 'icons.js'), `${banner}export const ICONS = ${JSON.stringify(out)};\n`);
console.log(`Wrote ${Object.keys(out).length} icons to js/icons.js`);
